def build():
    items = []
    for (slug, title, sub, cat, avg, mn, mx, ov, why, tips, note, mkw, en) in RAW:
        items.append({
            "slug": slug, "title": title, "subtitle": sub, "category": cat,
            "average_price": avg, "min_price": mn, "max_price": mx, "overseas_price_jpy": ov,
            "why_it_sells": why, "selling_tips": tips,
            "listing_template": template(title, sub, note),
            "mercari_search_keyword": mkw, "_en": en,
        })
    return items


def main() -> None:
    skip_images = "--no-images" in sys.argv
    assert len(RAW) == 30 and len({r[4] for r in RAW}) == 30, "need 30 items with unique prices"
    conn = connect()
    stats = {"rakuten": 0, "wikimedia": 0, "fallback": 0}
    for it in build():
        en = it.pop("_en")
        img = dict(FALLBACK) if skip_images else fetch_image(it["mercari_search_keyword"], en)
        it.update(img)
        upsert_item(conn, it)
        stats[img["image_source_type"]] += 1
        print("[{:>9}] {}".format(img["image_source_type"], it["slug"]))
        if not skip_images:
            time.sleep(0.4)
    print("\nDone. 30 items seeded -> images: {}".format(stats))


if __name__ == "__main__":
    main()
